/**
 * Private aria2 daemon lifecycle.
 *
 * Security properties:
 * - loopback-only RPC (`rpc-listen-all=false`) on a random port;
 * - a 256-bit random RPC secret, written to a 0600 config file instead of argv,
 *   so it never appears in `ps` output;
 * - `stop-with-process=<pi pid>` makes aria2 exit if Pi crashes, so no orphan
 *   daemon keeps downloading behind the user's back;
 * - no shell is ever involved: spawn receives an argv array.
 *
 * Downloads never overwrite: `continue=true`, `allow-overwrite=false`, and
 * `auto-file-renaming=false` mean an existing destination is an error, not a
 * silent replacement.
 */

import { type ChildProcess, spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { chmod, mkdir, readdir, stat, unlink, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { join } from "node:path";
import { Aria2Client } from "./rpc.ts";

export class DaemonStartError extends Error {
	readonly stderr: string;

	constructor(message: string, stderr = "") {
		super(message);
		this.name = "DaemonStartError";
		this.stderr = stderr;
	}
}

export interface DaemonHandle {
	client: Aria2Client;
	pid: number | undefined;
	port: number;
	proc: ChildProcess;
	version: string;
	/** Last stderr output, with the RPC secret redacted. */
	stderrTail(): string;
	/** Run `callback` when the daemon exits. Returns an unsubscribe function. */
	onExit(callback: (code: number | null, signal: NodeJS.Signals | null) => void): () => void;
	/** Stop the daemon. Idempotent and safe to call twice. */
	shutdown(): Promise<void>;
}

export interface StartDaemonOptions {
	binary: string;
	/** aria2's default download directory. */
	defaultDir: string;
	/** Directory for the private config file. Created with mode 0700. */
	stateDir: string;
	/** Pi's PID for `--stop-with-process`. Omit to let the daemon outlive Pi. */
	stopWithPid?: number;
	split?: number;
	maxConcurrent?: number;
	maxSpeed?: string;
	enableDht?: boolean;
	readyTimeoutMs?: number;
}

const READY_TIMEOUT_MS = 8000;
const MAX_ATTEMPTS = 3;

function sleep(ms: number): Promise<void> {
	return new Promise((resolve) => setTimeout(resolve, ms));
}

/** Ask the OS for a free loopback port. The port is not held until aria2 binds it. */
function freePort(): Promise<number> {
	return new Promise((resolve, reject) => {
		const server = createServer();
		server.unref();
		server.once("error", reject);
		server.listen(0, "127.0.0.1", () => {
			const address = server.address();
			const port = address && typeof address === "object" ? address.port : 0;
			server.close(() => (port ? resolve(port) : reject(new Error("could not allocate a loopback port"))));
		});
	});
}

function randomPort(): number {
	// BitTorrent's listen port cannot be 0. Pick from the ephemeral range.
	return 20000 + Math.floor(Math.random() * 40000);
}

/** RPC endpoint is always literal loopback HTTP. */
export function loopbackEndpoint(port: number): string {
	return `http://127.0.0.1:${port}/jsonrpc`;
}

function redact(text: string, secret: string): string {
	if (!text) return "";
	return text.split(secret).join("<redacted>").split(`token:${secret}`).join("token:<redacted>");
}

function configLines(port: number, secret: string, options: StartDaemonOptions): string[] {
	const split = Math.min(16, Math.max(1, options.split ?? 8));
	const maxConcurrent = Math.min(20, Math.max(1, options.maxConcurrent ?? 5));
	const lines = [
		"# Generated by pi-aria2 for this session. Deleted when the daemon stops.",
		"enable-rpc=true",
		"rpc-listen-all=false",
		"rpc-allow-origin-all=false",
		`rpc-listen-port=${port}`,
		`rpc-secret=${secret}`,
		"rpc-max-request-size=16M",
		"continue=true",
		"auto-file-renaming=false",
		"allow-overwrite=false",
		"check-integrity=false",
		"file-allocation=none",
		"remote-time=true",
		"content-disposition-default-utf8=true",
		`max-concurrent-downloads=${maxConcurrent}`,
		`split=${split}`,
		`max-connection-per-server=${split}`,
		"min-split-size=1M",
		"max-tries=5",
		"retry-wait=2",
		"timeout=60",
		"connect-timeout=30",
		"max-download-result=200",
		"auto-save-interval=30",
		"summary-interval=0",
		"console-log-level=warn",
		"log-level=warn",
		"quiet=true",
		"download-result=hide",
		// BitTorrent: no local peer discovery, stop after the download completes,
		// keep .torrent metadata in memory. DHT is opt-in because it opens a UDP port.
		`enable-dht=${options.enableDht === true ? "true" : "false"}`,
		"bt-enable-lpd=false",
		"enable-peer-exchange=true",
		"follow-torrent=mem",
		"seed-time=0",
	];
	if (options.enableDht) lines.push("dht-listen-port=6881-6999");
	if (options.maxSpeed) lines.push(`max-overall-download-limit=${options.maxSpeed}`);
	return lines;
}

async function pruneRuntime(runtimeDir: string): Promise<void> {
	try {
		const now = Date.now();
		for (const name of await readdir(runtimeDir)) {
			if (!name.startsWith("aria2-") || !name.endsWith(".conf")) continue;
			const path = join(runtimeDir, name);
			try {
				const info = await stat(path);
				if (now - info.mtimeMs > 24 * 60 * 60 * 1000) await unlink(path);
			} catch {
				// Another session may have cleaned it up first.
			}
		}
	} catch {
		// Best effort only.
	}
}


async function spawnOnce(options: StartDaemonOptions, port: number, secret: string): Promise<DaemonHandle> {
	const runtimeDir = join(options.stateDir, "runtime");
	await mkdir(runtimeDir, { recursive: true, mode: 0o700 });
	await chmod(runtimeDir, 0o700).catch(() => {});
	const configPath = join(
		runtimeDir,
		`aria2-${process.pid}-${port}-${randomBytes(4).toString("hex")}.conf`,
	);
	await writeFile(configPath, `${configLines(port, secret, options).join("\n")}\n`, { mode: 0o600 });

	const args = [
		"--conf-path",
		configPath,
		"--dir",
		options.defaultDir,
		"--listen-port",
		String(randomPort()),
	];
	if (options.stopWithPid) args.push("--stop-with-process", String(options.stopWithPid));

	let stderrBuffer = "";
	const proc = spawn(options.binary, args, {
		stdio: ["ignore", "ignore", "pipe"],
		windowsHide: true,
		env: process.env,
	});
	proc.stderr?.setEncoding("utf8");
	proc.stderr?.on("data", (chunk: string) => {
		stderrBuffer = `${stderrBuffer}${chunk}`.slice(-8192);
	});
	const stderr = () => redact(stderrBuffer, secret);
	let spawnError: Error | undefined;
	proc.once("error", (error) => {
		spawnError = error;
	});
	const client = new Aria2Client({ endpoint: loopbackEndpoint(port), secret, timeoutMs: 8000 });
	const deadline = Date.now() + (options.readyTimeoutMs ?? READY_TIMEOUT_MS);
	let lastError: unknown;
	let version = "";
	while (Date.now() < deadline) {
		if (spawnError) {
			await unlink(configPath).catch(() => {});
			throw new DaemonStartError(`could not start aria2c: ${spawnError.message}`, stderr());
		}
		if (proc.exitCode !== null) {
			await unlink(configPath).catch(() => {});
			throw new DaemonStartError(`aria2c exited (code ${proc.exitCode})`, stderr());
		}
		try {
			const info = await Promise.race([
				client.version({ timeoutMs: 1500 }),
				new Promise<never>((_, reject) => setTimeout(() => reject(new Error("timeout")), 1600)),
			]);
			version = info.version;
			break;
		} catch (error) {
			lastError = error;
			await sleep(100);
		}
	}

	if (!version) {
		proc.kill("SIGKILL");
		await unlink(configPath).catch(() => {});
		const detail = lastError instanceof Error ? lastError.message : String(lastError ?? "unknown error");
		throw new DaemonStartError(`aria2 RPC did not become ready: ${detail}`, stderr());
	}

	let stopped = false;
	let exitedFlag = false;
	let exitCode: number | null = null;
	let exitSignal: NodeJS.Signals | null = null;
	const exitListeners = new Set<(code: number | null, signal: NodeJS.Signals | null) => void>();
	proc.once("exit", (code, signal) => {
		exitedFlag = true;
		exitCode = code;
		exitSignal = signal;
		for (const listener of exitListeners) {
			try {
				listener(code, signal);
			} catch {
				// Listener errors must not crash the daemon wrapper.
			}
		}
	});

	const shutdown = async (): Promise<void> => {
		if (stopped) return;
		stopped = true;
		try {
			await client.shutdown({ timeoutMs: 2500 });
		} catch {
			// The daemon may already be gone; fall through to signals.
		}
		if (!(await waitForExit(proc, 2500))) {
			proc.kill("SIGTERM");
			if (!(await waitForExit(proc, 1500))) {
				proc.kill("SIGKILL");
				await waitForExit(proc, 1000);
			}
		}
		await unlink(configPath).catch(() => {});
	};

	// If anything below throws, the caller retries; clean up this attempt first.
	return {
		client,
		pid: proc.pid,
		port,
		proc,
		version,
		stderrTail: stderr,
		onExit(callback) {
			if (exitedFlag) {
				callback(exitCode, exitSignal);
				return () => {};
			}
			exitListeners.add(callback);
			return () => {
				exitListeners.delete(callback);
			};
		},
		shutdown,
	};
}

function waitForExit(proc: ChildProcess, timeoutMs: number): Promise<boolean> {
	if (proc.exitCode !== null) return Promise.resolve(true);
	return new Promise((resolve) => {
		const timer = setTimeout(() => {
			proc.removeListener("exit", onExit);
			resolve(false);
		}, timeoutMs);
		const onExit = () => {
			clearTimeout(timer);
			resolve(true);
		};
		proc.once("exit", onExit);
	});
}

/**
 * Start a private daemon, retrying on port races or transient startup failures.
 * Throws {@link DaemonStartError} with a redacted stderr tail.
 */
export async function startDaemon(options: StartDaemonOptions): Promise<DaemonHandle> {
	await pruneRuntime(join(options.stateDir, "runtime"));
	let lastError: unknown;
	for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
		const port = await freePort();
		const secret = randomBytes(32).toString("hex");
		try {
			return await spawnOnce(options, port, secret);
		} catch (error) {
			lastError = error;
			if (attempt === MAX_ATTEMPTS) break;
			// Port races and bind errors are worth a retry; a missing binary is not.
			if (error instanceof DaemonStartError && /not found|EACCES|permission/i.test(error.message)) break;
			await sleep(150);
		}
	}
	if (lastError instanceof DaemonStartError) throw lastError;
	throw new DaemonStartError(lastError instanceof Error ? lastError.message : String(lastError));
}
